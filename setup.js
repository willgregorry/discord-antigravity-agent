const fs = require('fs');
const path = require('path');
const readline = require('readline');
const { execSync } = require('child_process');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

const askQuestion = (query) => new Promise((resolve) => rl.question(query, resolve));

async function runSetup() {
  console.log('\n======================================================');
  console.log('🤖 ANTIGRAVITY DISCORD AGENT - SETUP WIZARD');
  console.log('======================================================\n');
  console.log('Wizard ini akan memandu instalasi dan konfigurasi bot kamu.\n');

  // 1. Cek Node Version
  const nodeMajor = parseInt(process.versions.node.split('.')[0], 10);
  if (nodeMajor < 18) {
    console.warn(`⚠️ Peringatan: Versi Node.js kamu v${process.version}. Disarankan Node.js v18 atau lebih baru.`);
  } else {
    console.log(`✅ Node.js Version: ${process.version}`);
  }

  // 2. Cek Antigravity CLI (agy)
  try {
    const isWindows = process.platform === 'win32';
    const checkCmd = isWindows ? 'where agy' : 'which agy';
    execSync(checkCmd, { stdio: 'ignore' });
    console.log('✅ Antigravity CLI (agy) terdeteksi di PATH sistem.\n');
  } catch (_) {
    console.log('⚠️ Antigravity CLI (agy) belum terdeteksi di PATH.');
    console.log('   Pastikan kamu telah menginstal Antigravity CLI agar bot bisa menjalankan agen.\n');
  }

  // 3. Konfigurasi .env
  const envPath = path.join(__dirname, '.env');
  let overwriteEnv = true;

  if (fs.existsSync(envPath)) {
    const ans = await askQuestion('❓ File .env sudah ada. Mau konfigurasi ulang? (y/N): ');
    if (ans.trim().toLowerCase() !== 'y') {
      overwriteEnv = false;
      console.log('⏩ Melewati konfigurasi .env');
    }
  }

  if (overwriteEnv) {
    console.log('\n--- 1. Konfigurasi Discord & Kredensial ---');
    let token = '';
    while (!token) {
      token = (await askQuestion('👉 Masukkan DISCORD_BOT_TOKEN: ')).trim();
      if (!token) console.log('❌ Token tidak boleh kosong!');
    }

    const userId = (await askQuestion('👉 Masukkan Discord User ID kamu (opsional, untuk whitelist keamanan): ')).trim();
    const geminiKey = (await askQuestion('👉 Masukkan GEMINI_API_KEY (opsional): ')).trim();

    console.log('\n--- 2. Direktori Kerja Default ---');
    const defaultSuggestedDir = process.cwd();
    const inputDir = (await askQuestion(`👉 Direktori kerja default [${defaultSuggestedDir}]: `)).trim();
    const selectedDir = inputDir || defaultSuggestedDir;

    if (!fs.existsSync(selectedDir)) {
      try {
        fs.mkdirSync(selectedDir, { recursive: true });
        console.log(`📁 Berhasil membuat direktori: ${selectedDir}`);
      } catch (err) {
        console.warn(`⚠️ Gagal membuat direktori: ${err.message}`);
      }
    }

    const envContent = [
      '# Generated by Antigravity Agent Setup Wizard',
      `DISCORD_TOKEN=${token}`,
      `GEMINI_API_KEY=${geminiKey}`,
      `DEFAULT_DIR=${selectedDir}`,
      `ALLOWED_USER_IDS=${userId}`
    ].join('\n');

    fs.writeFileSync(envPath, envContent, 'utf8');
    console.log('✅ File .env berhasil dibuat!');
  }

  // 4. Inisialisasi config.json jika belum ada
  const configPath = path.join(__dirname, 'config.json');
  const configExamplePath = path.join(__dirname, 'config.example.json');
  if (!fs.existsSync(configPath) && fs.existsSync(configExamplePath)) {
    fs.copyFileSync(configExamplePath, configPath);
    console.log('✅ File config.json dibuat dari config.example.json.');
  }

  // 5. Inisialisasi sessions.json jika belum ada
  const sessionsPath = path.join(__dirname, 'sessions.json');
  if (!fs.existsSync(sessionsPath)) {
    fs.writeFileSync(sessionsPath, JSON.stringify({}, null, 2), 'utf8');
    console.log('✅ File sessions.json diinisialisasi.');
  }

  // 6. Buat folder temp_downloads jika belum ada
  const tempDir = path.join(__dirname, 'temp_downloads');
  if (!fs.existsSync(tempDir)) {
    fs.mkdirSync(tempDir, { recursive: true });
    console.log('✅ Folder temp_downloads disiapkan.');
  }

  console.log('\n======================================================');
  console.log('🎉 SETUP SELESAI!');
  console.log('======================================================');
  console.log('Untuk menjalankan bot:');
  console.log('  npm start\n');
  console.log('Atau di Windows, kamu bisa langsung double-click start.bat\n');

  rl.close();
}

runSetup().catch(err => {
  console.error('\n❌ Terjadi kesalahan saat setup:', err);
  rl.close();
});
